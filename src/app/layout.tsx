import type { Metadata } from 'next';
import { Manrope } from 'next/font/google';
// Import CSS của react-toastify ở đây thay vì @import trong globals.css:
// Turbopack (next dev --turbo) bắt lỗi "@import rules must precede all rules" khi @import nằm sau @tailwind.
import 'react-toastify/dist/ReactToastify.css';
import './globals.css';
import { ThemeProvider } from '@/components/theme-provider';
import AppProvider from '@/components/app-provider';
import { ToastContainer } from 'react-toastify';
import NextTopLoader from 'nextjs-toploader';

export const metadata: Metadata = {
  title: `B'Restaurant`,
  description: 'Generated by create next app',
};

const manropo = Manrope({ subsets: ['latin'], variable: '--font-manrope' });

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en" suppressHydrationWarning>
      <body className={manropo.className}>
        <ThemeProvider
          attribute="class"
          defaultTheme="system"
          enableSystem
          disableTransitionOnChange
        >
          <NextTopLoader showSpinner={false} color="hsl(var(--foreground))" />
          <AppProvider>
            <main>{children}</main>
            <ToastContainer
              hideProgressBar={true}
              autoClose={3000}
              theme="light"
            />
          </AppProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}
